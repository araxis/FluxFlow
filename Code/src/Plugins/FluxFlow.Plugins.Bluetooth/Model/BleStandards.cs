using System.Globalization;
using System.Text;

namespace FluxFlow.Components.Bluetooth;

public enum BleUuidKind { Service, Characteristic, Descriptor }
public sealed record BleAssignedUuid(ushort Number, string Name, BleUuidKind Kind, string Support)
{
    public Guid Id => BleStandards.Uuid(Number);
    public string Label => $"{Name} · 0x{Number:X4}";
}

// Deliberately curated; not a claim to implement the complete Assigned Numbers registry.
public static class BleStandards
{
    public static Guid Uuid(ushort number) => Guid.Parse($"0000{number:x4}-0000-1000-8000-00805f9b34fb");
    public static bool IsBluetoothUuid(Guid id) => id.ToString().EndsWith("-0000-1000-8000-00805f9b34fb", StringComparison.OrdinalIgnoreCase);
    public static Guid NewCustomUuid()
    {
        Guid id;
        do { id = Guid.NewGuid(); } while (IsBluetoothUuid(id));
        return id;
    }
    public static bool IsSystemService(Guid id) => new ushort[] { 0x1800, 0x1801, 0x180a, 0x1813 }.Any(number => Uuid(number) == id);
    public static IReadOnlyList<BleAssignedUuid> Entries { get; } = Array.AsReadOnly<BleAssignedUuid>([
        new(0x1800, "Generic Access", BleUuidKind.Service, "Windows-managed"),
        new(0x1801, "Generic Attribute", BleUuidKind.Service, "Windows-managed"),
        new(0x180a, "Device Information", BleUuidKind.Service, "Windows-managed; client discovery supported"),
        new(0x180f, "Battery Service", BleUuidKind.Service, "Basic Battery Level template"),
        new(0x1804, "Tx Power", BleUuidKind.Service, "Read-only template; supply actual transmit power"),
        new(0x1813, "Scan Parameters", BleUuidKind.Service, "Windows-managed"),
        new(0x2a19, "Battery Level", BleUuidKind.Characteristic, "Unsigned byte, 0–100 percent"),
        new(0x2a07, "Tx Power Level", BleUuidKind.Characteristic, "Signed byte, -100–20 dBm"),
        new(0x2a29, "Manufacturer Name String", BleUuidKind.Characteristic, "UTF-8"),
        new(0x2a24, "Model Number String", BleUuidKind.Characteristic, "UTF-8"),
        new(0x2a25, "Serial Number String", BleUuidKind.Characteristic, "UTF-8"),
        new(0x2901, "Characteristic User Description", BleUuidKind.Descriptor, "Use the User description field"),
        new(0x2902, "Client Characteristic Configuration", BleUuidKind.Descriptor, "Generated by Windows for Notify/Indicate"),
        new(0x2904, "Characteristic Presentation Format", BleUuidKind.Descriptor, "Not editable in this companion")
    ]);
    public static IEnumerable<BleAssignedUuid> Search(string? text, BleUuidKind kind) => Entries.Where(entry => entry.Kind == kind &&
        (string.IsNullOrWhiteSpace(text) || $"{entry.Label} {entry.Id}".Contains(text, StringComparison.OrdinalIgnoreCase)));

    public static BleService BatteryTemplate(bool notify = false) => new()
    {
        Id = Uuid(0x180f), Name = "Battery Service",
        Characteristics = [new() { Id = Uuid(0x2a19), Properties = BleCharacteristicProperties.Read | (notify ? BleCharacteristicProperties.Notify : 0),
            InitialValue = new() { Encoding = BleValueEncoding.Hex, Data = "64" } }]
    };

    public static BleService TxPowerTemplate(sbyte dbm = 0) => new()
    {
        Id = Uuid(0x1804), Name = "Tx Power",
        Characteristics = [new() { Id = Uuid(0x2a07), Properties = BleCharacteristicProperties.Read,
            InitialValue = Encode(Uuid(0x2a07), dbm.ToString(CultureInfo.InvariantCulture)) }]
    };

    public static bool HasCodec(Guid id) => id == Uuid(0x2a19) || id == Uuid(0x2a07) ||
        new ushort[] { 0x2a29, 0x2a24, 0x2a25 }.Any(number => Uuid(number) == id);
    public static string Decode(Guid id, byte[] bytes)
    {
        if (id == Uuid(0x2a19))
        {
            if (bytes.Length != 1 || bytes[0] > 100) throw new ArgumentException("Battery Level requires one byte between 0 and 100.");
            return bytes[0].ToString(CultureInfo.InvariantCulture);
        }
        if (id == Uuid(0x2a07))
        {
            if (bytes.Length != 1 || unchecked((sbyte)bytes[0]) is < -100 or > 20) throw new ArgumentException("Tx Power Level requires one signed byte between -100 and 20 dBm.");
            return unchecked((sbyte)bytes[0]).ToString(CultureInfo.InvariantCulture);
        }
        if (!HasCodec(id)) throw new ArgumentException("No standard codec is available for this UUID. Keep the explicit raw bytes.");
        return new UTF8Encoding(false, true).GetString(bytes);
    }
    public static BlePayload Encode(Guid id, string value)
    {
        byte[] bytes;
        if (id == Uuid(0x2a19)) bytes = [byte.Parse(value, CultureInfo.InvariantCulture)];
        else if (id == Uuid(0x2a07)) bytes = [unchecked((byte)sbyte.Parse(value, CultureInfo.InvariantCulture))];
        else if (HasCodec(id)) bytes = new UTF8Encoding(false, true).GetBytes(value);
        else throw new ArgumentException("No standard codec is available for this UUID.");
        _ = Decode(id, bytes);
        var result = new BlePayload { Encoding = BleValueEncoding.Hex, Data = Convert.ToHexString(bytes) };
        _ = result.Decode();
        return result;
    }
}
